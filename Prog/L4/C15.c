#include <stdio.h>

int main() {
    int x, y, i, j;
    printf("Введите значения в формате x y i j \n");
    scanf("%d %d %d %d", &x, &y, &i, &j);

    y = (((x >> i) & 1) << j) | (y & ~(1 << j)); 
    // x>>i сдвигает нужны бит на кранюю правую позицию, затем умножаем все на побитоваое "0..001" чтобы от числа остался только нужны бит
    // и сдвигаем его на j позицию где его нужно поставить. 1<<j выбирает нужный нам бит на позиции j. Используем инвентирование ~
    // так получим (1..111101111), 0 нужная нам позиция. и умножаем его на у в итоге у не изменится т.к. умножается на единицы а нужный бит станет 0
    //А дальше используем или и получаем сложение нужной позиции 1+0.

    printf("x = %d\n", x);
    printf("y = %d\n", y);

    return 0;
}